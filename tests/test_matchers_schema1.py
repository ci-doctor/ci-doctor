"""Schema 1 in a registry: the index entry, skipping what this ci-doctor can't read, and `matchers.exclude`."""

import logging

import pytest
import yaml

from ci_doctor.config.schemas.matchers import MatchersConfig
from ci_doctor.engine import compile_plan
from ci_doctor.errors import SetupError
from ci_doctor.matchers.registry import load, resolve
from tests.support import write_registry

DESC = "An output description long enough for the rules."
RUFF = {
    "schema": 1,
    "description": "Ruff, the Python linter and formatter, in a test registry.",
    "tags": ["python", "lint"],
    "define": {"RULE": "[A-Z]+[0-9]+"},
    "outputs": {
        "check": {"description": DESC, "match": {"regex": "^%{RULE} "}},
        "format": {"description": DESC, "role": "gate", "match": {"template": "Would reformat: "}},
    },
}
DISK = {"schema": 1, "role": "issue", "description": DESC, "tags": ["infra"], "match": {"template": "ENOSPC"}}


@pytest.fixture
def registry(tmp_path):
    """A registry with a two-output and a one-output schema 1 matcher, and a curated bundle."""
    return write_registry(tmp_path / "reg", {"ruff": RUFF, "disk_full": DISK}, {"all": ["python", "infra"]})


def _cfg(root, include, exclude=()):
    return MatchersConfig(registries={"fx": str(root)}, include=include, exclude=list(exclude))


def test_the_index_lists_schema_ecosystem_tags_and_outputs(registry):
    """A client chooses and skips a matcher from the index alone."""
    index = yaml.safe_load((registry / "index.yaml").read_text())
    assert index["matchers"]["ruff"] | {"sha256": "-", "path": "-"} == {
        "path": "-",
        "sha256": "-",
        "description": RUFF["description"],
        "tags": ["python", "lint"],
        "schema": 1,
        "ecosystem": "python",
        "outputs": ["check", "format"],
    }
    assert "outputs" not in index["matchers"]["disk_full"]


def test_ecosystem_bundles_are_generated_from_the_folders(registry):
    """`official/python` is everything under `matchers/python/`; nobody edits it by hand."""
    text = (registry / "bundles" / "python.yaml").read_text()
    assert text.startswith("# Generated by `ci-doctor matchers index`")
    assert yaml.safe_load(text)["include"] == ["ruff"]
    assert set(yaml.safe_load((registry / "index.yaml").read_text())["bundles"]) == {"all", "infra", "python"}


def test_loaded_outputs_carry_the_alias_and_the_dot(registry):
    """`fx/ruff.check`: the id the prompt shows and `matchers.exclude` names."""
    specs = load(_cfg(registry, ["fx/all"]))
    assert [o.output.id for o in compile_plan(specs).outputs] == [
        "fx/ruff.check",
        "fx/ruff.format",
        "fx/disk_full",
    ]


def test_exclude_drops_one_output(registry):
    """Excluded outputs are left out when the Plan is compiled."""
    cfg = _cfg(registry, ["fx/ruff"], ["fx/ruff.format"])
    assert [o.output.id for o in compile_plan(load(cfg), cfg.exclude).outputs] == ["fx/ruff.check"]


def test_an_exclude_that_names_nothing_is_a_setup_error(registry):
    """A typo in `matchers.exclude` fails setup instead of silently excluding nothing."""
    with pytest.raises(SetupError, match=r"fx/ruff\.fromat \(did you mean fx/ruff\.format\?\)"):
        load(_cfg(registry, ["fx/ruff"], ["fx/ruff.fromat"]))


def test_an_exclude_must_be_an_output_reference():
    """The config schema rejects anything not shaped `<registry>/<matcher>[.<output>]`."""
    with pytest.raises(ValueError, match="not an output reference"):
        MatchersConfig(exclude=["ruff.format"])


def _newer(registry):
    """Mark ruff as schema 2 in the index, as a registry ahead of this ci-doctor would."""
    path = registry / "index.yaml"
    path.write_text(
        path.read_text().replace(
            "    schema: 1\n    tags: [python, lint]", "    schema: 2\n    tags: [python, lint]"
        )
    )


def test_a_newer_schema_in_a_bundle_is_skipped_with_a_warning(registry, caplog):
    """The rest of the bundle still loads; the skip is logged, before anything is fetched."""
    _newer(registry)
    with caplog.at_level(logging.WARNING):
        resolved = resolve(_cfg(registry, ["fx/all"]))
    assert list(resolved.matchers) == ["fx/disk_full"]
    assert "fx/ruff needs a newer ci-doctor (schema 2); skipped from fx/all" in caplog.text


def test_a_newer_schema_named_directly_fails_setup(registry):
    """The user asked for it by name, so silently dropping it would be wrong."""
    _newer(registry)
    with pytest.raises(SetupError, match=r"fx/ruff needs a newer ci-doctor \(schema 2\)"):
        resolve(_cfg(registry, ["fx/ruff"]))


def test_a_newer_schema_in_the_file_itself_fails_setup(registry):
    """An index that lags its file can't sneak an unknown schema past the loader."""
    path = registry / "matchers/python/ruff/matcher.yaml"
    path.write_text(path.read_text().replace("schema: 1", "schema: 3"))
    with pytest.raises(SetupError, match=r"needs a newer ci-doctor \(schema 3\)"):
        load(_cfg(registry, ["fx/ruff"]))
